-- ============================================================================
--  Phase 4 — Listings Engine
--
--  · properties gain the identity they never had, so a re-list or a second
--    provider updates one house instead of creating a second one
--  · a refresh is a diff: new / price change / removed / relisted / unchanged,
--    each with an audit row and a price-history entry
--  · v_listings_enriched carries listing + property + latest eligibility so the
--    All Listings page filters and sorts in the database
--
--  Run in Supabase SQL Editor after 0004. Idempotent.
-- ============================================================================

-- ───────────────────────── property identity ────────────────────────────────
alter table properties add column if not exists unit text;

-- Phase 1 inserted a fresh properties row for every listing it had not seen
-- before, with no lookup and no constraint. The same house arriving from a
-- second provider, or re-listed under a new MLS number, became a second
-- property — splitting its notes, pipeline status and eligibility history.
-- Merge any such rows onto the lowest id, then make it impossible again.
do $$
declare v_dupes int;
begin
  drop table if exists _property_merge;
  create unlogged table _property_merge as
    select p.id as dupe_id,
           min(p.id) over (partition by p.market_id, p.address_norm, coalesce(p.unit, '')) as keeper_id
      from properties p
     where p.address_norm is not null;
  delete from _property_merge where dupe_id = keeper_id;

  select count(*) into v_dupes from _property_merge;
  if v_dupes = 0 then
    raise notice 'No duplicate properties to merge.';
  else
    raise notice 'Merging % duplicate properties onto their earliest row.', v_dupes;

    -- user-owned rows move to the keeper; drop the loser where the keeper
    -- already has one, since these tables are unique per property (or per user)
    delete from saved_properties s using _property_merge m
     where s.property_id = m.dupe_id
       and exists (select 1 from saved_properties k where k.property_id = m.keeper_id and k.user_id = s.user_id);
    update saved_properties s set property_id = m.keeper_id from _property_merge m where s.property_id = m.dupe_id;

    delete from acquisition_pipeline a using _property_merge m
     where a.property_id = m.dupe_id
       and exists (select 1 from acquisition_pipeline k where k.property_id = m.keeper_id);
    update acquisition_pipeline a set property_id = m.keeper_id from _property_merge m where a.property_id = m.dupe_id;

    delete from property_features f using _property_merge m
     where f.property_id = m.dupe_id
       and exists (select 1 from property_features k where k.property_id = m.keeper_id and k.feature_key = f.feature_key);
    update property_features f set property_id = m.keeper_id from _property_merge m where f.property_id = m.dupe_id;

    update property_notes n    set property_id = m.keeper_id from _property_merge m where n.property_id = m.dupe_id;
    update hoa_verifications h set property_id = m.keeper_id from _property_merge m where h.property_id = m.dupe_id;
    update listings l          set property_id = m.keeper_id from _property_merge m where l.property_id = m.dupe_id;

    -- everything else hanging off a property is derived and regenerated by a
    -- re-run, so let the cascade take it
    delete from properties p using _property_merge m where p.id = m.dupe_id;
  end if;
  drop table if exists _property_merge;
end $$;

create unique index if not exists properties_identity_uniq
