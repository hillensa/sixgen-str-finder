-- ───────────────────────── the All Listings source ──────────────────────────
-- One row per listing carrying its property and its latest eligibility, so the
-- page can filter and sort in the database rather than pulling everything.
drop view if exists v_listings_enriched;
create view v_listings_enriched with (security_invoker = true) as
  select
    l.id                        as listing_id,
    l.market_id, l.provider, l.external_id, l.status,
    l.list_price, l.original_price, l.previous_price, l.price_changed_at,
    l.days_on_market, l.listed_at, l.url, l.primary_photo, l.brokerage, l.agent,
    l.first_seen, l.last_seen, l.removed_at,
    case when l.original_price is not null and l.original_price > 0 and l.list_price is not null
         then round(((l.original_price - l.list_price)::numeric / l.original_price) * 100, 1) end as price_drop_pct,
    (l.original_price - l.list_price)                                                             as price_drop,
    p.id                        as property_id,
    p.address, p.address_norm, p.unit, p.zip, p.lat, p.lng,
    p.beds, p.baths, p.sqft, p.lot_sqft, p.year_built, p.property_type, p.stories,
    p.garage, p.pool, p.basement, p.finished_basement,
    p.hoa_status, p.hoa_fee_monthly, p.hoa_name,
    p.parcel_id, p.parcel_match_confidence,
    case when p.sqft is not null and p.sqft > 0 and l.list_price is not null
         then round(l.list_price::numeric / p.sqft, 0) end                                        as price_per_sqft,
    e.classification, e.summary as eligibility_summary,
    e.zone_code, e.zoning_treatment, e.cup_required,
    e.spacing_result, e.nearest_str_distance_ft, e.density_result,
    e.rules_version, e.checked_at as eligibility_checked_at
  from listings l
  join properties p on p.id = l.property_id
  left join v_property_eligibility e on e.property_id = p.id;

-- ───────────────────────── dashboard / refresh summaries ────────────────────
create or replace function fn_listing_summary(p_market text)
returns table (
  active int, pending int, sold int, removed int,
  screened int, green int, yellow int, red int,
  median_price numeric, price_drops int)
language sql stable as $$
  select
    count(*) filter (where status = 'active' and removed_at is null)::int,
    count(*) filter (where status = 'pending')::int,
    count(*) filter (where status = 'sold')::int,
    count(*) filter (where status = 'removed' or removed_at is not null)::int,
    count(*) filter (where classification is not null)::int,
    count(*) filter (where classification = 'GREEN')::int,
    count(*) filter (where classification = 'YELLOW')::int,
    count(*) filter (where classification = 'RED')::int,
    percentile_cont(0.5) within group (order by list_price)
      filter (where status = 'active' and list_price is not null)::numeric,
    count(*) filter (where price_drop > 0)::int
  from v_listings_enriched where market_id = p_market;
$$;

/** Properties whose eligibility is older than the current rules version. */
create or replace function fn_stale_eligibility(p_market text)
returns table (property_id bigint, rules_version text, checked_at timestamptz)
language sql stable as $$
  select v.property_id, v.rules_version, v.checked_at
    from v_property_eligibility v
    join properties pr on pr.id = v.property_id
    join jurisdictions j on j.market_id = pr.market_id
   where pr.market_id = p_market
     and v.rules_version is distinct from fn_rules_version(j.id);
$$;
