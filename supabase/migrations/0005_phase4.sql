/**
 * Find the property a listing belongs to: canonical address first, then a
 * coordinate match inside a tolerance, so a provider that spells the address
 * differently does not create a second house.
 * Returns null when there is genuinely no match — the caller then inserts.
 */
create or replace function fn_match_property(
  p_market text, p_address_norm text, p_unit text,
  p_lat double precision, p_lng double precision, p_tolerance_ft numeric default 60)
returns bigint language plpgsql stable as $$
declare v_id bigint; srid int;
begin
  select id into v_id from properties
   where market_id = p_market and address_norm = p_address_norm
     and coalesce(unit, '') = coalesce(p_unit, '')
   limit 1;
  if v_id is not null then return v_id; end if;

  if p_lat is null or p_lng is null then return null; end if;
  select m.srid_feet into srid from markets m where m.id = p_market;
  if srid is null then return null; end if;

  select p.id into v_id
    from properties p
   where p.market_id = p_market and p.geom is not null
     and coalesce(p.unit, '') = coalesce(p_unit, '')
     and ST_DWithin(ST_Transform(p.geom, srid),
                    ST_Transform(ST_SetSRID(ST_MakePoint(p_lng, p_lat), 4326), srid),
                    p_tolerance_ft)
   order by ST_Distance(ST_Transform(p.geom, srid),
                        ST_Transform(ST_SetSRID(ST_MakePoint(p_lng, p_lat), 4326), srid))
   limit 1;
  return v_id;
end $$;

